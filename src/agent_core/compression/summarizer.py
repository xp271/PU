"""
LLM-based conversation compression — the ``compress()`` entry point.

Replaces older conversation rounds with a concise summary generated by a
dedicated LLM call (no tools, small max_tokens budget).  The summary is
injected as a single ``<conversation_summary>`` user message so the model
can pick up from where it left off.

Retry loop:  when the post-compression consistency check fails, the
verification errors are fed back to the LLM in the next attempt's prompt.
After all retries are exhausted a ``CompressionError`` is raised so the
caller (``query()``) can fall back to ``hard_truncate``.
"""

from __future__ import annotations

import logging
from dataclasses import dataclass, field
from typing import Any

from ..llm.events import InternalEvent
from ..models import CompressionConfig, ModelId
from ..tools.registry import registered_tools
from .consistency import verify_compression, CompressionConsistency
from .prompts import (
    COMPRESSION_REQUEST,
    CONVERSATION_SUMMARY,
    RETRY_FEEDBACK,
    ROUND_HEADER,
    TOOL_RESULT_TRUNCATED,
)
from .trigger import _partition_rounds

logger = logging.getLogger("agent_core.compression")


# ---------------------------------------------------------------------------
# Exceptions
# ---------------------------------------------------------------------------


class CompressionError(Exception):
    """Raised when compression fails irrecoverably (all retries exhausted)."""


# ---------------------------------------------------------------------------
# Data types
# ---------------------------------------------------------------------------


@dataclass
class CompressionAttempt:
    """Record of a single compression LLM call + its verification result."""

    attempt: int
    summary: str
    verification: CompressionConsistency
    tokens_consumed: int = 0
    input_tokens_consumed: int = 0
    output_tokens_consumed: int = 0
    error: str | None = None


# ---------------------------------------------------------------------------
# Public API
# ---------------------------------------------------------------------------


async def compress(
    client,  # BaseClient instance (duck-typed to avoid circular import)
    messages: list[dict[str, Any]],
    system: str | None,
    model_id: ModelId,
    config: CompressionConfig,
) -> tuple[list[dict[str, Any]], str, list[CompressionAttempt]]:
    """Compress older conversation rounds into a summary.

    Parameters
    ----------
    client:
        An already-instantiated ``BaseClient`` subclass.
    messages:
        The full message list in Anthropic content-block format.
    system:
        The system prompt string (passed through unchanged to the
        summarization call).
    config:
        Compression tuning parameters.

    Returns
    -------
    (compressed_messages, summary, attempts)
        *compressed_messages* replaces the old rounds with a single
        ``<conversation_summary>`` user message followed by the recent
        rounds unchanged.

    Raises
    ------
    CompressionError
        When all retry attempts are exhausted without a valid result.
    """
    # -- 1. Partition into rounds -------------------------------------------
    rounds = _partition_rounds(messages)

    if len(rounds) <= config.keep_recent_rounds:
        # Nothing to compress — return original unchanged
        return messages, "", []

    old_rounds = rounds[:-config.keep_recent_rounds]
    recent_rounds = rounds[-config.keep_recent_rounds:]

    # -- 2. Retry loop ------------------------------------------------------
    attempts: list[CompressionAttempt] = []
    last_error: str | None = None

    for attempt_num in range(config.max_retries + 1):
        # Build prompt (includes previous errors on retry)
        prompt = _build_compression_prompt(
            old_rounds=old_rounds,
            preview_chars=config.tool_result_preview_chars,
            previous_errors=last_error,
            custom_template=config.prompt_template,
        )

        # Call LLM for summarization
        try:
            summary, input_tok, output_tok = await _call_llm_for_summary(
                client=client,
                prompt=prompt,
                system=system,
                max_tokens=config.summary_max_tokens,
            )
        except Exception as exc:
            attempts.append(CompressionAttempt(
                attempt=attempt_num + 1,
                summary="",
                verification=CompressionConsistency(
                    valid=False,
                    errors=[f"LLM call failed: {exc}"],
                ),
                error=str(exc),
            ))
            last_error = f"LLM call failed: {exc}"
            logger.warning(
                "Compression LLM call failed (attempt %d/%d): %s",
                attempt_num + 1, config.max_retries + 1, exc,
            )
            if attempt_num < config.max_retries:
                continue
            break

        # Assemble compressed message list
        compressed = _build_compressed_messages(summary, recent_rounds)

        # Verify consistency
        verification = verify_compression(
            original_messages=messages,
            compressed_messages=compressed,
            old_rounds=old_rounds,
            recent_rounds=recent_rounds,
            summary=summary,
        )
        verification.input_tokens_consumed = input_tok
        verification.output_tokens_consumed = output_tok

        attempts.append(CompressionAttempt(
            attempt=attempt_num + 1,
            summary=summary,
            verification=verification,
            tokens_consumed=input_tok + output_tok,
            input_tokens_consumed=input_tok,
            output_tokens_consumed=output_tok,
        ))

        if verification.valid:
            # Success — return compressed result
            return compressed, summary, attempts

        # Verification failed — prepare for retry
        last_error = "; ".join(verification.errors)
        logger.warning(
            "Compression verification failed (attempt %d/%d): %s. %s",
            attempt_num + 1,
            config.max_retries + 1,
            last_error,
            "Retrying..." if attempt_num < config.max_retries else "All retries exhausted.",
        )

    # All retries exhausted
    raise CompressionError(
        f"Compression verification failed after {config.max_retries + 1} "
        f"attempt(s): {last_error}"
    )


# ---------------------------------------------------------------------------
# Internal helpers
# ---------------------------------------------------------------------------


def _build_compression_prompt(
    old_rounds: list[list[dict[str, Any]]],
    preview_chars: int,
    previous_errors: str | None = None,
    custom_template: str | None = None,
) -> str:
    """Build the user prompt that asks the LLM to summarise history.

    Uses *custom_template* if provided, otherwise the built-in
    ``COMPRESSION_REQUEST`` from ``prompts.py``.
    """

    # Render old rounds in a compact, readable format
    parts: list[str] = []
    for i, rnd in enumerate(old_rounds, 1):
        parts.append(ROUND_HEADER.format(round_num=i))
        for msg in rnd:
            role = msg.get("role", "unknown")
            for block in msg.get("content", []):
                if not isinstance(block, dict):
                    continue
                btype = block.get("type", "")
                if btype == "text":
                    text = str(block.get("text", ""))
                    parts.append(f"{role}: {text}")
                elif btype == "tool_use":
                    name = block.get("name", "?")
                    inp = _shorten(str(block.get("input", {})), preview_chars)
                    parts.append(f"{role} (tool_use: {name}, input: {inp})")
                elif btype == "tool_result":
                    content = str(block.get("content", ""))
                    if len(content) > preview_chars:
                        preview = _shorten(content, preview_chars)
                        output = TOOL_RESULT_TRUNCATED.format(
                            preview=preview, original_len=len(content)
                        )
                    else:
                        output = content
                    parts.append(f"tool_result: {output}")

    conversation_text = "\n".join(parts)

    template = custom_template if custom_template is not None else COMPRESSION_REQUEST
    prompt = template.format(
        preview_chars=preview_chars,
        conversation_text=conversation_text,
    )

    if previous_errors:
        prompt += "\n\n" + RETRY_FEEDBACK.format(previous_errors=previous_errors)

    return prompt


def _shorten(text: str, max_chars: int) -> str:
    """Truncate *text* to *max_chars*, appending a marker if cut."""
    if len(text) <= max_chars:
        return text
    return text[:max_chars] + f"... [truncated, original ~{len(text)} chars]"


async def _call_llm_for_summary(
    client,  # BaseClient
    prompt: str,
    system: str | None,
    max_tokens: int,
) -> tuple[str, int, int]:
    """Call the LLM (without tools) to generate a summary.

    Returns (summary_text, input_tokens, output_tokens).
    """
    compression_messages = [
        {"role": "user", "content": [{"type": "text", "text": prompt}]},
    ]

    # Get empty tool list (no tools for summarization)
    empty_tools = client.__class__.convert_tools([])

    summary_parts: list[str] = []
    input_tokens = 0
    output_tokens = 0

    async for event in client.stream_messages(
        messages=compression_messages,
        tools=empty_tools,
        system=system,
        max_tokens=max_tokens,
        turn_index=0,  # Not counted in the main turn budget
    ):
        match event.type:
            case "assistant_text":
                summary_parts.append(event.content)  # type: ignore[attr-defined]
            case "token_counts":
                input_tokens = event.input_tokens  # type: ignore[attr-defined]
                output_tokens = event.output_tokens  # type: ignore[attr-defined]
            case "error":
                raise CompressionError(
                    f"LLM summarization failed: {event.message}"  # type: ignore[attr-defined]
                )
            case "stop":
                break

    summary = "".join(summary_parts)
    return summary, input_tokens, output_tokens


def _build_compressed_messages(
    summary: str,
    recent_rounds: list[list[dict[str, Any]]],
) -> list[dict[str, Any]]:
    """Assemble the final compressed message list.

    [summary_message] + [all messages from recent_rounds]
    """
    summary_message: dict[str, Any] = {
        "role": "user",
        "content": [
            {
                "type": "text",
                "text": CONVERSATION_SUMMARY.format(summary=summary),
            }
        ],
    }

    flat_recent = [msg for rnd in recent_rounds for msg in rnd]
    return [summary_message] + flat_recent
